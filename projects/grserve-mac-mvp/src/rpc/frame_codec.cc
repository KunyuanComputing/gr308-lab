Error Failure(ErrorCode code, std::string message) {
  return Error::From(code, std::move(message));
}

Status ValidateBlockingDescriptor(int fd, const char* operation) {
  const int flags = fcntl(fd, F_GETFL);
  if (flags < 0) {
    return Status{Failure(ErrorCode::kInternal,
                          std::string("frame ") + operation +
                              ": invalid descriptor")};
  }
  if ((flags & O_NONBLOCK) != 0) {
    return Status{Failure(ErrorCode::kInvalidArgument,
                          std::string("frame ") + operation +
                              ": nonblocking descriptors are unsupported")};
  }
  return Status::Ok();
}

ssize_t WriteWithoutSigpipe(int fd, const void* data, std::size_t size) {
  int socket_type = 0;
  socklen_t socket_type_size = sizeof(socket_type);
  const bool is_socket =
      getsockopt(fd, SOL_SOCKET, SO_TYPE, &socket_type, &socket_type_size) == 0;
  if (!is_socket) {
    // write(2), unlike send(2), is valid for pipes and regular files. Block
    // SIGPIPE only in this thread and consume solely the signal generated by
    // this call, preserving any signal that was already pending.
    sigset_t sigpipe_set;
    sigset_t previous_mask;
    sigset_t pending_before;
    sigemptyset(&sigpipe_set);
    sigaddset(&sigpipe_set, SIGPIPE);
    const int mask_error =
        pthread_sigmask(SIG_BLOCK, &sigpipe_set, &previous_mask);
    if (mask_error != 0) {
      errno = mask_error;
      return -1;
    }
    const bool had_pending_sigpipe =
        sigpending(&pending_before) == 0 &&
        sigismember(&pending_before, SIGPIPE) == 1;
    const ssize_t result = write(fd, data, size);
    const int write_error = errno;
    if (result < 0 && write_error == EPIPE && !had_pending_sigpipe) {
      sigset_t pending_after;
      if (sigpending(&pending_after) == 0 &&
          sigismember(&pending_after, SIGPIPE) == 1) {
        int consumed_signal = 0;
        (void)sigwait(&sigpipe_set, &consumed_signal);
      }
    }
    const int restore_error =
        pthread_sigmask(SIG_SETMASK, &previous_mask, nullptr);
    if (restore_error != 0) {
      errno = restore_error;
      return -1;
    }
    errno = write_error;
    return result;
  }
#if defined(__APPLE__) && defined(SO_NOSIGPIPE)
  const int enabled = 1;
  if (setsockopt(fd, SOL_SOCKET, SO_NOSIGPIPE, &enabled, sizeof(enabled)) != 0) {
    // Darwin may report EINVAL when the peer disappeared before the option
    // could be applied. Do not attempt a potentially signal-raising send.
    if (errno == EINVAL || errno == ENOTCONN) {
      errno = EPIPE;
    }
    return -1;
  }
  return send(fd, data, size, 0);
#elif defined(__linux__) && defined(MSG_NOSIGNAL)
  return send(fd, data, size, MSG_NOSIGNAL);
#else
  return send(fd, data, size, 0);
#endif
}

enum class ReadExactResult { kComplete, kCleanEof, kPartialEof };

StatusOr<ReadExactResult> ReadExact(const FrameReader::ReadFunction& read_fn,
                                    int fd, void* output, std::size_t size,
                                    bool header) {
  auto* bytes = static_cast<std::uint8_t*>(output);
  std::size_t offset = 0;
  while (offset < size) {
    const ssize_t count = read_fn(fd, bytes + offset, size - offset);
    if (count > 0) {
      offset += static_cast<std::size_t>(count);
      continue;
    }
    if (count == 0) {
      if (header && offset == 0) {
        return StatusOr<ReadExactResult>(ReadExactResult::kCleanEof);
      }
      return StatusOr<ReadExactResult>(ReadExactResult::kPartialEof);
    }
    if (errno == EINTR) {
      continue;
    }
    if (errno == EAGAIN || errno == EWOULDBLOCK) {
      return StatusOr<ReadExactResult>(Failure(
          ErrorCode::kResourceExhausted,
          "frame read: blocking descriptor returned EAGAIN"));
    }
    if (errno == ECONNRESET) {
      return StatusOr<ReadExactResult>(
          Failure(ErrorCode::kInternal, "frame read: peer disconnected"));
    }
    return StatusOr<ReadExactResult>(
        Failure(ErrorCode::kInternal, "frame read: system read failed"));
  }
  return StatusOr<ReadExactResult>(ReadExactResult::kComplete);
}

Status WriteExact(const FrameWriter::WriteFunction& write_fn, int fd,
                  const void* input, std::size_t size) {
  const auto* bytes = static_cast<const std::uint8_t*>(input);
  std::size_t offset = 0;
  while (offset < size) {
    const ssize_t count = write_fn(fd, bytes + offset, size - offset);
    if (count > 0) {
      offset += static_cast<std::size_t>(count);
      continue;
    }
    if (count == 0) {
      return Status{Failure(ErrorCode::kInternal,
                            "frame write: write returned zero")};
    }
    if (errno == EINTR) {
      continue;
    }
    if (errno == EAGAIN || errno == EWOULDBLOCK) {
      return Status{Failure(ErrorCode::kResourceExhausted,
                            "frame write: blocking descriptor returned EAGAIN")};
    }
    if (errno == EPIPE || errno == ECONNRESET || errno == ENOTCONN) {
      return Status{Failure(ErrorCode::kInternal,
                            "frame write: peer disconnected")};
    }
    return Status{Failure(ErrorCode::kInternal,
                          "frame write: system write failed")};
  }
  return Status::Ok();
}

