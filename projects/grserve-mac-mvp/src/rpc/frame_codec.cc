FrameReader::FrameReader()
    : read_function_([](int fd, void* output, std::size_t size) {
        return read(fd, output, size);
      }) {}

FrameReader::FrameReader(ReadFunction read_function)
    : read_function_(std::move(read_function)) {}

StatusOr<std::optional<v1::ClientEnvelope>> FrameReader::ReadOne(int fd) const {
  const Status descriptor = ValidateBlockingDescriptor(fd, "read");
  if (!descriptor.ok()) {
    return StatusOr<std::optional<v1::ClientEnvelope>>(*descriptor.error());
  }

  std::uint32_t network_size = 0;
  auto header = ReadExact(read_function_, fd, &network_size, sizeof(network_size),
                          true);
  if (!header.ok()) {
    return StatusOr<std::optional<v1::ClientEnvelope>>(*header.error());
  }
  if (header.value() == ReadExactResult::kCleanEof) {
    return StatusOr<std::optional<v1::ClientEnvelope>>(std::nullopt);
  }
  if (header.value() == ReadExactResult::kPartialEof) {
    return StatusOr<std::optional<v1::ClientEnvelope>>(Failure(
        ErrorCode::kInternal, "frame read: EOF in 4-byte header"));
  }

  const std::uint32_t body_size = ntohl(network_size);
  if (body_size == 0) {
    return StatusOr<std::optional<v1::ClientEnvelope>>(Failure(
        ErrorCode::kInvalidArgument, "frame read: zero-length frame"));
  }
  if (body_size > kMaxFrameBytes) {
    return StatusOr<std::optional<v1::ClientEnvelope>>(Failure(
        ErrorCode::kInvalidArgument,
        "frame read: frame exceeds 4 MiB limit"));
  }

  std::vector<std::uint8_t> body(body_size);
  auto body_result =
      ReadExact(read_function_, fd, body.data(), body.size(), false);
  if (!body_result.ok()) {
    return StatusOr<std::optional<v1::ClientEnvelope>>(*body_result.error());
  }
  if (body_result.value() != ReadExactResult::kComplete) {
    return StatusOr<std::optional<v1::ClientEnvelope>>(
        Failure(ErrorCode::kInternal, "frame read: EOF in body"));
  }

  google::protobuf::io::ArrayInputStream array_input(
      body.data(), static_cast<int>(body.size()));
  google::protobuf::io::CodedInputStream coded_input(&array_input);
  coded_input.SetTotalBytesLimit(static_cast<int>(kMaxFrameBytes));
  coded_input.SetRecursionLimit(kFrameProtoRecursionLimit);
  v1::ClientEnvelope envelope;
  if (!envelope.ParseFromCodedStream(&coded_input) ||
      !coded_input.ConsumedEntireMessage()) {
    return StatusOr<std::optional<v1::ClientEnvelope>>(Failure(
        ErrorCode::kInvalidArgument,
        "frame read: invalid ClientEnvelope protobuf"));
  }
  return StatusOr<std::optional<v1::ClientEnvelope>>(
      std::optional<v1::ClientEnvelope>(std::move(envelope)));
}

FrameWriter::FrameWriter() : write_function_(WriteWithoutSigpipe) {}

FrameWriter::FrameWriter(WriteFunction write_function)
    : write_function_(std::move(write_function)) {}

Status FrameWriter::WriteOne(int fd,
                             const v1::ServerEnvelope& envelope) const {
  const Status descriptor = ValidateBlockingDescriptor(fd, "write");
  if (!descriptor.ok()) {
    return descriptor;
  }
  const std::size_t body_size = envelope.ByteSizeLong();
  if (body_size == 0) {
    return Status{Failure(ErrorCode::kInvalidArgument,
                          "frame write: zero-length frame")};
  }
  if (body_size > kMaxFrameBytes) {
    return Status{Failure(ErrorCode::kInvalidArgument,
                          "frame write: frame exceeds 4 MiB limit")};
  }

  std::string body;
  if (!envelope.SerializeToString(&body) || body.size() != body_size) {
    return Status{Failure(ErrorCode::kInternal,
                          "frame write: protobuf serialization failed")};
  }
  const std::uint32_t network_size =
      htonl(static_cast<std::uint32_t>(body_size));
  std::vector<std::uint8_t> frame(kFrameHeaderBytes + body.size());
  std::memcpy(frame.data(), &network_size, sizeof(network_size));
  std::memcpy(frame.data() + kFrameHeaderBytes, body.data(), body.size());
  return WriteExact(write_function_, fd, frame.data(), frame.size());
}

